"""Writes the band table of crates/model/src/skin_appearance/spectra_table.rs from downloaded sources.

Usage: python -I gen_spectra.py <dl dir> <out file>
Sources (downloaded 2026-11-19 into <dl dir>):
  cie/cmf_cie.csv  CIE 1931 2-degree CMFs, 1 nm (DOI 10.25039/CIE.DS.xvudnb9b)
  cie/d65.csv      CIE standard illuminant D65, 1 nm (DOI 10.25039/CIE.DS.hjfjmt59)
  omlc/hb.html     Prahl, tabulated molar extinction of HbO2 / Hb, 2 nm
  omlc/car.txt     Prahl / PhotochemCAD 2.1a, beta-carotene in hexane, 0.25 nm
"""
import re, sys

dl, out = sys.argv[1], sys.argv[2]

def csv_table(path):
    t = {}
    for line in open(path, encoding='utf-8-sig'):
        parts = line.strip().split(',')
        if len(parts) < 2:
            continue
        t[int(parts[0])] = [float(p) for p in parts[1:]]
    return t

cmf = csv_table(dl + '/cie/cmf_cie.csv')
d65 = csv_table(dl + '/cie/d65.csv')

hb = {}
text = re.sub(r'<[^>]*>', '', open(dl + '/omlc/hb.html', encoding='latin-1').read())
for line in text.splitlines():
    m = re.match(r'^\s*(\d+)\s+([0-9.]+)\s+([0-9.]+)\s*$', line)
    if m:
        hb[int(m.group(1))] = (float(m.group(2)), float(m.group(3)))

car = []
for line in open(dl + '/omlc/car.txt', encoding='latin-1'):
    if line.startswith('#') or not line.strip():
        continue
    a, b = line.split()
    car.append((float(a), float(b)))

def lerp_table(pairs, x):
    for (x0, y0), (x1, y1) in zip(pairs, pairs[1:]):
        if x0 <= x <= x1:
            return y0 + (y1 - y0) * (x - x0) / (x1 - x0)
    return None

def hb_at(nm):
    if nm in hb:
        return hb[nm]
    lo, hi = hb[nm - 1], hb[nm + 1]
    return ((lo[0] + hi[0]) / 2, (lo[1] + hi[1]) / 2)

def car_at(nm):
    v = lerp_table(car, nm)
    if v is None:
        return 0.0  # the source ends at 700 nm; beta-carotene does not absorb beyond it
    return max(v, 0.0)

rows = []
for nm in range(380, 781, 5):
    x, y, z = cmf[nm]
    o, d = hb_at(nm)
    rows.append((nm, x, y, z, d65[nm][0], o, d, round(car_at(nm), 1)))

with open(out, 'w', newline='\n') as f:
    f.write('//! The spectral band table of the pigment model: 81 bands, 380 to 780 nm in 5 nm steps.\n')
    f.write('//!\n')
    f.write('//! Generated by `tools/spectra/gen_spectra.py` from the downloaded sources, never\n')
    f.write('//! edited by hand. Columns: wavelength (nm); CIE 1931 2-degree colour-matching functions x, y, z\n')
    f.write('//! (CIE, DOI 10.25039/CIE.DS.xvudnb9b, 1 nm table sampled at the band); CIE standard illuminant\n')
    f.write('//! D65 relative power (CIE, DOI 10.25039/CIE.DS.hjfjmt59); molar extinction coefficients in\n')
    f.write('//! cm^-1/M of oxy- and deoxy-haemoglobin (S. Prahl, omlc.org/spectra/hemoglobin/summary.html,\n')
    f.write('//! 2 nm table, odd wavelengths the mean of their neighbours); molar extinction of beta-carotene in\n')
    f.write('//! hexane (PhotochemCAD 2.1a via S. Prahl, omlc.org/spectra/PhotochemCAD/data/041-abs.txt,\n')
    f.write('//! linearly interpolated, negative noise clamped to 0, 0 beyond the table\'s 700 nm end).\n')
    f.write('//! Provenance rows: `docs/data-provenance.md` (WP-13 spectral tables).\n')
    f.write('//!\n')
    f.write('//! Licence: the CIE columns (x, y, z, d65) are an 81-row subset of the CIE datasets above,\n')
    f.write('//! (c) CIE, licensed under CC BY-SA 4.0 (https://creativecommons.org/licenses/by-sa/4.0/);\n')
    f.write('//! changes: sampled at 5 nm, values unchanged. That subset is shared under the same licence\n')
    f.write('//! (owner decision, ADR-038). The Prahl and PhotochemCAD columns state no licence.\n\n')
    f.write('/// One band: `[nm, x, y, z, d65, hbo2, hb, carotene]`.\n')
    f.write('pub(super) type Band = [f64; 8];\n\n')
    f.write('/// The bands, shortest wavelength first.\n')
    f.write('#[rustfmt::skip]\n')
    f.write('pub(super) const BANDS: [Band; %d] = [\n' % len(rows))
    for r in rows:
        f.write('    [%s],\n' % ', '.join(repr(float(v)) for v in r))
    f.write('];\n')
print(len(rows), 'bands')
