//! The skin surface of the geometry pass: group 3 of `render/geometry.wgsl`, read by skin objects
//! whose [`crate::sss::SkinShading::surface`] is set (library `render/skin_surface.wgsl`).
//!
//! [`SkinSurface`] binds what the skin appearance system (`crate::skin`) produces:
//!
//! - the compositor's **resolved set**, specular array and baked inputs (zone masks, baked
//!   thickness) `[SKN-01]` `[SKN-11]` ([`SkinSurface::bind_compositor`]): the albedo (flushed by
//!   [`SurfaceSettings::flush`], `[SKN-31]`), the dual-lobe specular, the cavity, the meso normal,
//!   wetness and oiliness, and the scattering radii that set the profile width per pixel
//!   `[SHD-02]`;
//! - the **micro-detail exemplar** `[SKN-20]` `[SKN-21]` ([`SkinSurface::set_micro_detail`]):
//!   generated by `MicroDetailGpu`, converted by `render/detail_mips.wgsl` into mip-mapped slopes
//!   and slope moments, and sampled with the histogram-preserving tiling of `skin/antitile.wgsl`
//!   (variance-preserving blend of the slopes), rotated onto the skin-line (Langer) direction; the
//!   slope variance that filtering removes is added to the GGX `α²` of both lobes, so pores
//!   smaller than a pixel still roughen the highlight;
//! - the **wrinkle maps** and their activations `[SKN-30]` ([`SkinSurface::set_wrinkles`]);
//! - the per-UV-tile scale (millimetres of skin per UV unit, from the template's tile table) and
//!   the layer settings of [`SurfaceSettings`]: the oil / sweat coat and the lips' layered model
//!   `[SHD-06]`, the vellus sheen `[SHD-07]` `[SKN-22]`, micro-shadowing `[SHD-09]`.
//!
//! Until a source is bound, 1 × 1 neutral stand-ins fill its bindings, so the pass never needs
//! another layout. Every change rebuilds the one bind group (editor-time work); per frame the
//! renderer only binds it (`[PERF-R1]`, `[PERF-R4]`).
//!
//! Texture coordinates of a surfaced mesh carry the UV tile in the integer part of u
//! ([`crate::scene::Mesh::from_template`]).

use humanart_gpu::Gpu;
use humanart_gpu::cache::PipelineCache;
use humanart_model::skin_appearance::microdetail::ExemplarPlan;
use humanart_model::template::UvTile;

use crate::error::RenderError;
use crate::skin::SkinCompositor;
use crate::skin::microdetail::MicroDetailGpu;
use crate::skin::wrinkle::WrinkleGpu;

/// UV tiles the surface can address (the template has 8).
pub const MAX_UV_TILES: usize = 16;
/// Bytes of `SurfaceParams` in `render/skin_surface.wgsl`.
const PARAMS_BYTES: usize = MAX_UV_TILES * 16 + 4 * 16;
/// Workgroup edge of `render/detail_mips.wgsl`.
const GROUP: u32 = 8;
/// "No resolved tile" in the tile table.
const NO_TILE: f32 = -1.0;

/// The layer settings of surfaced skin. Every value is an artistic default until calibrated
/// against captures; none is measured.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct SurfaceSettings {
    /// Millimetres of skin per UV unit of each UV tile; 0 for a tile without surface data.
    pub mm_per_uv: [f32; MAX_UV_TILES],
    /// Micro-detail strength, 0..=2 (1: the exemplar's slopes as generated).
    pub detail_strength: f32,
    /// Strength of the pore cavity in micro-shadowing and occlusion, 0..=1 `[SHD-09]`.
    pub micro_shadowing: f32,
    /// Animated flush, 0..=1 `[SKN-31]`.
    pub flush: f32,
    /// Oil coat strength per unit of the resolved oiliness, 0..=1 `[SHD-06]`.
    pub oil_coat: f32,
    /// Perceptual roughness of the oil / sweat coat, 0..=1.
    pub coat_roughness: f32,
    /// Coat strength on the lips (lip zone mask), 0..=1.
    pub lip_coat: f32,
    /// Perceptual roughness of the lips' coat, 0..=1.
    pub lip_coat_roughness: f32,
    /// Factor on both lobe roughnesses on the lips, 0..=1.
    pub lip_roughness_scale: f32,
    /// Vellus sheen strength in a full fuzz zone (cheeks and nose), 0..=1; 35 % of it
    /// elsewhere, none on the lips (`humanart_model::skin_appearance::microdetail::vellus_lobe`).
    pub fuzz: f32,
    /// Sheen roughness of the vellus lobe, 0..=1.
    pub fuzz_width: f32,
    /// Seed of the anti-tiling offsets.
    pub seed: u32,
    /// Strength of the photographed skin colour detail, 0..=2 (1, the default: the tile as
    /// photographed; 1.5 read as speckles at portrait distance; [`SkinSurface::set_albedo_detail`]).
    pub albedo_detail: f32,
}

impl Default for SurfaceSettings {
    fn default() -> Self {
        Self {
            mm_per_uv: [0.0; MAX_UV_TILES],
            detail_strength: 1.0,
            micro_shadowing: 1.0,
            flush: 0.0,
            oil_coat: 0.2,
            coat_roughness: 0.3,
            lip_coat: 0.6,
            lip_coat_roughness: 0.15,
            lip_roughness_scale: 0.7,
            fuzz: 0.15,
            fuzz_width: 0.4,
            seed: 0x5eed_0001,
            albedo_detail: 1.0,
        }
    }
}

impl SurfaceSettings {
    /// The defaults with the scale of a template's UV tiles: `resolution / target texels per mm`
    /// millimetres per UV unit (the layout keeps the texel density uniform within a tile).
    pub fn for_tiles(tiles: &[UvTile]) -> Self {
        let mut settings = Self::default();
        for (slot, tile) in settings.mm_per_uv.iter_mut().zip(tiles) {
            let mm = tile.resolution as f32 / tile.target_texels_per_mm;
            *slot = if mm.is_finite() && mm > 0.0 { mm } else { 0.0 };
        }
        settings
    }

    /// Checks the ranges.
    pub fn validate(&self) -> Result<(), RenderError> {
        let in01 = |v: f32| (0.0..=1.0).contains(&v);
        if self.mm_per_uv.iter().any(|v| !v.is_finite() || *v < 0.0) {
            return Err(RenderError::InvalidParameter { what: "skin surface: mm per UV must be finite and >= 0" });
        }
        if !(0.0..=2.0).contains(&self.detail_strength)
            || !(0.0..=2.0).contains(&self.albedo_detail)
            || ![
                self.micro_shadowing,
                self.flush,
                self.oil_coat,
                self.coat_roughness,
                self.lip_coat,
                self.lip_coat_roughness,
                self.lip_roughness_scale,
                self.fuzz,
                self.fuzz_width,
            ]
            .into_iter()
            .all(in01)
        {
            return Err(RenderError::InvalidParameter { what: "skin surface: a layer setting is out of its range" });
        }
        Ok(())
    }

    /// `SurfaceParams` of `render/skin_surface.wgsl`.
    fn bytes(&self, exemplar_mm: f32, albedo_mm: f32, resolved_tiles: u32, wrinkles: bool) -> [u8; PARAMS_BYTES] {
        let mut out = [0_u8; PARAMS_BYTES];
        let mut words = [0_u32; PARAMS_BYTES / 4];
        for (t, mm) in self.mm_per_uv.iter().enumerate() {
            let resolved = if (t as u32) < resolved_tiles { t as f32 } else { NO_TILE };
            words[t * 4] = mm.to_bits();
            words[t * 4 + 1] = resolved.to_bits();
        }
        let reference = crate::sss::reference_radius_mm();
        let mean = (reference[0] + reference[1] + reference[2]) / 3.0;
        let tail = [
            exemplar_mm,
            self.detail_strength,
            self.micro_shadowing,
            self.flush,
            self.oil_coat,
            self.coat_roughness,
            self.lip_coat,
            self.lip_coat_roughness,
            self.fuzz,
            self.fuzz_width,
            self.lip_roughness_scale,
            if mean > 0.0 { 1.0 / mean } else { 0.0 },
        ];
        let start = MAX_UV_TILES * 4;
        for (w, v) in words[start..start + 12].iter_mut().zip(tail) {
            *w = v.to_bits();
        }
        words[start + 12] = self.seed;
        words[start + 13] = u32::from(wrinkles);
        // The colour detail tile's side in mm (0: none) and its strength.
        words[start + 14] = albedo_mm.to_bits();
        words[start + 15] = self.albedo_detail.to_bits();
        for (chunk, w) in out.as_chunks_mut::<4>().0.iter_mut().zip(words) {
            *chunk = w.to_le_bytes();
        }
        out
    }
}

/// Cache keys of the detail pipelines.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
enum Key {
    Shader,
    Layout,
    PipelineLayout,
    Convert,
    Downsample,
}

/// The views and buffers group 3 binds.
#[derive(Debug, Clone)]
struct Sources {
    resolved: wgpu::TextureView,
    specular: wgpu::TextureView,
    inputs: wgpu::TextureView,
    detail: wgpu::TextureView,
    wrinkle_maps: wgpu::TextureView,
    albedo_detail: wgpu::TextureView,
    activations: wgpu::Buffer,
    tile_slots: wgpu::Buffer,
}

/// The skin surface bind group and its sources. See the module documentation.
pub struct SkinSurface {
    layout: wgpu::BindGroupLayout,
    cache: PipelineCache<Key>,
    micro: Option<MicroDetailGpu>,
    params: wgpu::Buffer,
    clamp: wgpu::Sampler,
    repeat: wgpu::Sampler,
    neutral: Sources,
    sources: Sources,
    bind: wgpu::BindGroup,
    settings: SurfaceSettings,
    exemplar_mm: f32,
    resolved_tiles: u32,
    wrinkles: bool,
    detail_texture: Option<wgpu::Texture>,
    /// Side of the bound colour detail tile, mm (0: none).
    albedo_mm: f32,
    albedo_texture: Option<wgpu::Texture>,
}

impl std::fmt::Debug for SkinSurface {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("SkinSurface")
            .field("settings", &self.settings)
            .field("exemplar_mm", &self.exemplar_mm)
            .field("resolved_tiles", &self.resolved_tiles)
            .field("wrinkles", &self.wrinkles)
            .finish_non_exhaustive()
    }
}

fn layout_entry(binding: u32, ty: wgpu::BindingType) -> wgpu::BindGroupLayoutEntry {
    wgpu::BindGroupLayoutEntry { binding, visibility: wgpu::ShaderStages::FRAGMENT, ty, count: None }
}

const fn texture_type(dim: wgpu::TextureViewDimension) -> wgpu::BindingType {
    wgpu::BindingType::Texture {
        sample_type: wgpu::TextureSampleType::Float { filterable: true },
        view_dimension: dim,
        multisampled: false,
    }
}

const STORAGE: wgpu::BindingType = wgpu::BindingType::Buffer {
    ty: wgpu::BufferBindingType::Storage { read_only: true },
    has_dynamic_offset: false,
    min_binding_size: None,
};

/// A neutral 1 × 1 texture (`layers` layers) filled with `texel`.
fn neutral_texture(
    gpu: &Gpu,
    label: &str,
    format: wgpu::TextureFormat,
    layers: u32,
    texel: &[u8],
    dimension: wgpu::TextureViewDimension,
) -> wgpu::TextureView {
    let texture = gpu.device.create_texture(&wgpu::TextureDescriptor {
        label: Some(label),
        size: wgpu::Extent3d { width: 1, height: 1, depth_or_array_layers: layers },
        mip_level_count: 1,
        sample_count: 1,
        dimension: wgpu::TextureDimension::D2,
        format,
        usage: wgpu::TextureUsages::TEXTURE_BINDING | wgpu::TextureUsages::COPY_DST,
        view_formats: &[],
    });
    for layer in 0..layers {
        gpu.queue.write_texture(
            wgpu::TexelCopyTextureInfo {
                texture: &texture,
                mip_level: 0,
                origin: wgpu::Origin3d { x: 0, y: 0, z: layer },
                aspect: wgpu::TextureAspect::All,
            },
            texel,
            wgpu::TexelCopyBufferLayout { offset: 0, bytes_per_row: Some(texel.len() as u32), rows_per_image: Some(1) },
            wgpu::Extent3d { width: 1, height: 1, depth_or_array_layers: 1 },
        );
    }
    texture.create_view(&wgpu::TextureViewDescriptor { dimension: Some(dimension), ..Default::default() })
}

/// A whole-texture view as a 2D array.
fn array_view(texture: &wgpu::Texture) -> wgpu::TextureView {
    texture.create_view(&wgpu::TextureViewDescriptor {
        dimension: Some(wgpu::TextureViewDimension::D2Array),
        ..Default::default()
    })
}

impl SkinSurface {
    /// Creates the layout, the detail pipelines, the samplers and the neutral stand-ins.
    pub fn new(gpu: &Gpu) -> Result<Self, RenderError> {
        let device = &gpu.device;
        let d2 = wgpu::TextureViewDimension::D2;
        let array = wgpu::TextureViewDimension::D2Array;
        let sampler = wgpu::BindingType::Sampler(wgpu::SamplerBindingType::Filtering);
        let layout = device.create_bind_group_layout(&wgpu::BindGroupLayoutDescriptor {
            label: Some("skin surface"),
            entries: &[
                layout_entry(0, texture_type(array)),
                layout_entry(1, texture_type(array)),
                layout_entry(2, texture_type(array)),
                layout_entry(3, texture_type(d2)),
                layout_entry(4, texture_type(array)),
                layout_entry(5, STORAGE),
                layout_entry(6, STORAGE),
                layout_entry(7, sampler),
                layout_entry(8, sampler),
                layout_entry(
                    9,
                    wgpu::BindingType::Buffer {
                        ty: wgpu::BufferBindingType::Uniform,
                        has_dynamic_offset: false,
                        min_binding_size: None,
                    },
                ),
                layout_entry(10, texture_type(d2)),
            ],
        });
        let mut cache = PipelineCache::new(gpu);
        let source = humanart_shaders::compose("render/detail_mips.wgsl", &[])?.into_source();
        cache.shader(Key::Shader, "render/detail_mips.wgsl", &source)?;
        cache.bind_group_layout(
            Key::Layout,
            "skin detail mips",
            &[
                wgpu::BindGroupLayoutEntry {
                    binding: 0,
                    visibility: wgpu::ShaderStages::COMPUTE,
                    ty: wgpu::BindingType::Texture {
                        sample_type: wgpu::TextureSampleType::Float { filterable: false },
                        view_dimension: d2,
                        multisampled: false,
                    },
                    count: None,
                },
                wgpu::BindGroupLayoutEntry {
                    binding: 1,
                    visibility: wgpu::ShaderStages::COMPUTE,
                    ty: wgpu::BindingType::StorageTexture {
                        access: wgpu::StorageTextureAccess::WriteOnly,
                        format: wgpu::TextureFormat::Rgba16Float,
                        view_dimension: d2,
                    },
                    count: None,
                },
            ],
        )?;
        cache.pipeline_layout(Key::PipelineLayout, "skin detail mips", &[Some(&Key::Layout)])?;
        for (key, entry) in [(Key::Convert, "convert"), (Key::Downsample, "downsample")] {
            cache.compute_pipeline(key, |parts| {
                Ok(parts.device.create_compute_pipeline(&wgpu::ComputePipelineDescriptor {
                    label: Some("skin detail mips"),
                    layout: Some(parts.pipeline_layout(&Key::PipelineLayout)?),
                    module: parts.shader(&Key::Shader)?,
                    entry_point: Some(entry),
                    compilation_options: wgpu::PipelineCompilationOptions::default(),
                    cache: None,
                }))
            })?;
        }
        cache.mark_warm();
        let params = device.create_buffer(&wgpu::BufferDescriptor {
            label: Some("skin surface params"),
            size: PARAMS_BYTES as u64,
            usage: wgpu::BufferUsages::UNIFORM | wgpu::BufferUsages::COPY_DST,
            mapped_at_creation: false,
        });
        let clamp = device.create_sampler(&wgpu::SamplerDescriptor {
            label: Some("skin surface clamp"),
            mag_filter: wgpu::FilterMode::Linear,
            min_filter: wgpu::FilterMode::Linear,
            mipmap_filter: wgpu::MipmapFilterMode::Linear,
            ..Default::default()
        });
        let repeat = device.create_sampler(&wgpu::SamplerDescriptor {
            label: Some("skin surface detail"),
            address_mode_u: wgpu::AddressMode::Repeat,
            address_mode_v: wgpu::AddressMode::Repeat,
            mag_filter: wgpu::FilterMode::Linear,
            min_filter: wgpu::FilterMode::Linear,
            mipmap_filter: wgpu::MipmapFilterMode::Linear,
            anisotropy_clamp: 1,
            ..Default::default()
        });
        let half = |v: f32| half_bits(v).to_le_bytes();
        let zero16 = [0_u8; 8];
        // Cavity 1, no detail: the stand-ins change nothing.
        let detail_texel: Vec<u8> = [0.0, 0.0, 0.0, 1.0].iter().flat_map(|&v| half(v)).collect();
        let storage = |label: &str, words: &[u32]| {
            let bytes: Vec<u8> = words.iter().flat_map(|w| w.to_le_bytes()).collect();
            let buffer = device.create_buffer(&wgpu::BufferDescriptor {
                label: Some(label),
                size: bytes.len() as u64,
                usage: wgpu::BufferUsages::STORAGE | wgpu::BufferUsages::COPY_DST,
                mapped_at_creation: false,
            });
            gpu.queue.write_buffer(&buffer, 0, &bytes);
            buffer
        };
        let neutral = Sources {
            resolved: neutral_texture(
                gpu,
                "skin surface resolved",
                wgpu::TextureFormat::Rgba16Float,
                4,
                &zero16,
                array,
            ),
            specular: neutral_texture(gpu, "skin surface specular", wgpu::TextureFormat::Rgba8Unorm, 1, &[0; 4], array),
            inputs: neutral_texture(gpu, "skin surface inputs", wgpu::TextureFormat::Rgba8Unorm, 4, &[0; 4], array),
            detail: neutral_texture(gpu, "skin surface detail", wgpu::TextureFormat::Rgba16Float, 1, &detail_texel, d2),
            wrinkle_maps: neutral_texture(
                gpu,
                "skin surface wrinkles",
                wgpu::TextureFormat::Rgba16Float,
                3,
                &zero16,
                array,
            ),
            albedo_detail: neutral_texture(
                gpu,
                "skin surface colour detail",
                wgpu::TextureFormat::Rgba8Unorm,
                1,
                &[128, 128, 128, 255],
                d2,
            ),
            activations: storage("skin surface activations", &[0, 0]),
            tile_slots: storage("skin surface wrinkle slots", &[u32::MAX; MAX_UV_TILES]),
        };
        let bind = Self::make_bind(device, &layout, &neutral, &params, &clamp, &repeat);
        let surface = Self {
            layout,
            cache,
            micro: None,
            params,
            clamp,
            repeat,
            sources: neutral.clone(),
            neutral,
            bind,
            settings: SurfaceSettings::default(),
            exemplar_mm: 0.0,
            resolved_tiles: 0,
            wrinkles: false,
            detail_texture: None,
            albedo_mm: 0.0,
            albedo_texture: None,
        };
        surface.write_params(gpu);
        Ok(surface)
    }

    fn make_bind(
        device: &wgpu::Device,
        layout: &wgpu::BindGroupLayout,
        s: &Sources,
        params: &wgpu::Buffer,
        clamp: &wgpu::Sampler,
        repeat: &wgpu::Sampler,
    ) -> wgpu::BindGroup {
        let view = wgpu::BindingResource::TextureView;
        device.create_bind_group(&wgpu::BindGroupDescriptor {
            label: Some("skin surface"),
            layout,
            entries: &[
                wgpu::BindGroupEntry { binding: 0, resource: view(&s.resolved) },
                wgpu::BindGroupEntry { binding: 1, resource: view(&s.specular) },
                wgpu::BindGroupEntry { binding: 2, resource: view(&s.inputs) },
                wgpu::BindGroupEntry { binding: 3, resource: view(&s.detail) },
                wgpu::BindGroupEntry { binding: 4, resource: view(&s.wrinkle_maps) },
                wgpu::BindGroupEntry { binding: 5, resource: s.activations.as_entire_binding() },
                wgpu::BindGroupEntry { binding: 6, resource: s.tile_slots.as_entire_binding() },
                wgpu::BindGroupEntry { binding: 7, resource: wgpu::BindingResource::Sampler(clamp) },
                wgpu::BindGroupEntry { binding: 8, resource: wgpu::BindingResource::Sampler(repeat) },
                wgpu::BindGroupEntry { binding: 9, resource: params.as_entire_binding() },
                wgpu::BindGroupEntry { binding: 10, resource: view(&s.albedo_detail) },
            ],
        })
    }

    fn rebind(&mut self, gpu: &Gpu) {
        self.bind = Self::make_bind(&gpu.device, &self.layout, &self.sources, &self.params, &self.clamp, &self.repeat);
        self.write_params(gpu);
    }

    fn write_params(&self, gpu: &Gpu) {
        gpu.queue.write_buffer(
            &self.params,
            0,
            &self.settings.bytes(self.exemplar_mm, self.albedo_mm, self.resolved_tiles, self.wrinkles),
        );
    }

    /// The layout of group 3 (used by the geometry pipeline layout).
    pub const fn layout(&self) -> &wgpu::BindGroupLayout {
        &self.layout
    }

    /// The bind group of group 3.
    pub const fn bind_group(&self) -> &wgpu::BindGroup {
        &self.bind
    }

    /// The settings in use.
    pub const fn settings(&self) -> &SurfaceSettings {
        &self.settings
    }

    /// Detail pipelines created after [`SkinSurface::new`] (always 0).
    pub fn late_pipelines(&self) -> u32 {
        self.cache.stats().late
    }

    /// Replaces the settings (a uniform write; nothing is recreated).
    ///
    /// # Errors
    /// [`RenderError::InvalidParameter`] for a value out of its range.
    pub fn set_settings(&mut self, gpu: &Gpu, settings: SurfaceSettings) -> Result<(), RenderError> {
        settings.validate()?;
        self.settings = settings;
        self.write_params(gpu);
        Ok(())
    }

    /// Binds a compositor's resolved set, specular array and inputs; UV tile `t` reads resolved
    /// tile `t` for `t` below the compositor's tile count. Re-bind after recreating the compositor.
    ///
    /// # Errors
    /// [`RenderError::TooLarge`] when the compositor has more tiles than [`MAX_UV_TILES`].
    pub fn bind_compositor(&mut self, gpu: &Gpu, compositor: &SkinCompositor) -> Result<(), RenderError> {
        let tiles = compositor.desc().tiles;
        if tiles as usize > MAX_UV_TILES {
            return Err(RenderError::TooLarge {
                what: "skin compositor tiles",
                value: u64::from(tiles),
                limit: MAX_UV_TILES as u64,
            });
        }
        self.sources.resolved = array_view(compositor.resolved());
        self.sources.specular = array_view(compositor.specular());
        self.sources.inputs = array_view(compositor.inputs());
        self.resolved_tiles = tiles;
        self.rebind(gpu);
        Ok(())
    }

    /// Unbinds the compositor (surfaced skin falls back to the material's values).
    pub fn unbind_compositor(&mut self, gpu: &Gpu) {
        self.sources.resolved = self.neutral.resolved.clone();
        self.sources.specular = self.neutral.specular.clone();
        self.sources.inputs = self.neutral.inputs.clone();
        self.resolved_tiles = 0;
        self.rebind(gpu);
    }

    /// Binds the wrinkle maps, activations and tile slots of `wrinkles` `[SKN-30]`. The caller
    /// records `WrinkleGpu::record_activate` after the deformer's strain passes each frame.
    pub fn set_wrinkles(&mut self, gpu: &Gpu, wrinkles: &WrinkleGpu) {
        self.sources.wrinkle_maps = wrinkles.maps_view().clone();
        self.sources.activations = wrinkles.activations().clone();
        self.sources.tile_slots = wrinkles.tile_slots().clone();
        self.wrinkles = true;
        self.rebind(gpu);
    }

    /// Unbinds the wrinkle maps.
    pub fn clear_wrinkles(&mut self, gpu: &Gpu) {
        self.sources.wrinkle_maps = self.neutral.wrinkle_maps.clone();
        self.sources.activations = self.neutral.activations.clone();
        self.sources.tile_slots = self.neutral.tile_slots.clone();
        self.wrinkles = false;
        self.rebind(gpu);
    }

    /// Generates `plan`'s exemplar on the GPU (`MicroDetailGpu`, created on first use), converts
    /// it to mip-mapped slopes and binds it `[SKN-20]`. Editor-time: allocates the textures and
    /// submits its own command buffer.
    ///
    /// # Errors
    /// The generator's and the device's errors.
    pub fn set_micro_detail(&mut self, gpu: &Gpu, plan: &ExemplarPlan) -> Result<(), RenderError> {
        if self.micro.is_none() {
            self.micro = Some(MicroDetailGpu::new(gpu)?);
        }
        let Some(micro) = self.micro.as_ref() else {
            return Err(RenderError::InvalidParameter { what: "skin surface: micro-detail generator missing" });
        };
        let mut encoder =
            gpu.device.create_command_encoder(&wgpu::CommandEncoderDescriptor { label: Some("skin micro-detail") });
        let exemplar = micro.generate(gpu, &mut encoder, plan)?;
        let size = exemplar.size;
        let mips = 32 - size.leading_zeros();
        let texture = gpu.device.create_texture(&wgpu::TextureDescriptor {
            label: Some("skin detail slopes"),
            size: wgpu::Extent3d { width: size, height: size, depth_or_array_layers: 1 },
            mip_level_count: mips,
            sample_count: 1,
            dimension: wgpu::TextureDimension::D2,
            format: wgpu::TextureFormat::Rgba16Float,
            usage: wgpu::TextureUsages::TEXTURE_BINDING | wgpu::TextureUsages::STORAGE_BINDING,
            view_formats: &[],
        });
        let level = |mip: u32| {
            texture.create_view(&wgpu::TextureViewDescriptor {
                base_mip_level: mip,
                mip_level_count: Some(1),
                ..Default::default()
            })
        };
        let source = exemplar.detail.create_view(&wgpu::TextureViewDescriptor::default());
        let layout = self
            .cache
            .get_bind_group_layout(&Key::Layout)
            .ok_or(humanart_gpu::GpuError::Stale { what: "skin detail layout" })?;
        let mut groups = Vec::with_capacity(mips as usize);
        for mip in 0..mips {
            let input = if mip == 0 { source.clone() } else { level(mip - 1) };
            let output = level(mip);
            groups.push(gpu.device.create_bind_group(&wgpu::BindGroupDescriptor {
                label: Some("skin detail mip"),
                layout,
                entries: &[
                    wgpu::BindGroupEntry { binding: 0, resource: wgpu::BindingResource::TextureView(&input) },
                    wgpu::BindGroupEntry { binding: 1, resource: wgpu::BindingResource::TextureView(&output) },
                ],
            }));
        }
        let pipeline = |key| {
            self.cache.get_compute_pipeline(&key).ok_or(humanart_gpu::GpuError::Stale { what: "skin detail pipeline" })
        };
        let (convert, downsample) = (pipeline(Key::Convert)?, pipeline(Key::Downsample)?);
        // One pass per level: each reads the level the previous pass wrote.
        for (mip, group) in groups.iter().enumerate() {
            let side = (size >> mip).max(1);
            let mut pass = encoder.begin_compute_pass(&wgpu::ComputePassDescriptor {
                label: Some("skin detail mip"),
                timestamp_writes: None,
            });
            pass.set_pipeline(if mip == 0 { convert } else { downsample });
            pass.set_bind_group(0, group, &[]);
            pass.dispatch_workgroups(side.div_ceil(GROUP), side.div_ceil(GROUP), 1);
        }
        gpu.queue.submit([encoder.finish()]);
        self.sources.detail = texture.create_view(&wgpu::TextureViewDescriptor::default());
        self.detail_texture = Some(texture);
        self.exemplar_mm = plan.params.tile_mm();
        self.rebind(gpu);
        Ok(())
    }

    /// Binds the photographed skin colour detail tile
    /// (`humanart_model::skin_appearance::albedo_detail`): `levels` is its RGBA8 mip chain (level
    /// 0 `side`², each next level half, down to 1 × 1) of encoded log ratios, `side_mm` the skin
    /// it covers. Editor-time: allocates the texture.
    ///
    /// # Errors
    /// [`RenderError::InvalidParameter`] for a side that is not a power of two, levels that do not
    /// halve to 1 × 1, or a non-positive size in mm.
    pub fn set_albedo_detail(
        &mut self,
        gpu: &Gpu,
        side: u32,
        side_mm: f32,
        levels: &[Vec<u8>],
    ) -> Result<(), RenderError> {
        let bad = RenderError::InvalidParameter { what: "skin surface: colour detail mips do not match the side" };
        if !side.is_power_of_two() || side > 4096 || !(side_mm > 0.0 && side_mm.is_finite()) {
            return Err(bad);
        }
        let count = 32 - side.leading_zeros();
        if levels.len() != count as usize {
            return Err(bad);
        }
        for (mip, level) in levels.iter().enumerate() {
            let s = (side >> mip).max(1) as usize;
            if level.len() != s * s * 4 {
                return Err(bad);
            }
        }
        let texture = gpu.device.create_texture(&wgpu::TextureDescriptor {
            label: Some("skin colour detail"),
            size: wgpu::Extent3d { width: side, height: side, depth_or_array_layers: 1 },
            mip_level_count: count,
            sample_count: 1,
            dimension: wgpu::TextureDimension::D2,
            format: wgpu::TextureFormat::Rgba8Unorm,
            usage: wgpu::TextureUsages::TEXTURE_BINDING | wgpu::TextureUsages::COPY_DST,
            view_formats: &[],
        });
        for (mip, level) in levels.iter().enumerate() {
            let s = (side >> mip).max(1);
            gpu.queue.write_texture(
                wgpu::TexelCopyTextureInfo {
                    texture: &texture,
                    mip_level: mip as u32,
                    origin: wgpu::Origin3d::ZERO,
                    aspect: wgpu::TextureAspect::All,
                },
                level,
                wgpu::TexelCopyBufferLayout { offset: 0, bytes_per_row: Some(s * 4), rows_per_image: Some(s) },
                wgpu::Extent3d { width: s, height: s, depth_or_array_layers: 1 },
            );
        }
        self.sources.albedo_detail = texture.create_view(&wgpu::TextureViewDescriptor::default());
        self.albedo_texture = Some(texture);
        self.albedo_mm = side_mm;
        self.rebind(gpu);
        Ok(())
    }

    /// Unbinds the micro-detail.
    pub fn clear_micro_detail(&mut self, gpu: &Gpu) {
        self.sources.detail = self.neutral.detail.clone();
        self.detail_texture = None;
        self.exemplar_mm = 0.0;
        self.rebind(gpu);
    }
}

/// IEEE half-precision bits of `v` (round to nearest even; finite inputs in the half range).
fn half_bits(v: f32) -> u16 {
    let bits = v.to_bits();
    let sign = ((bits >> 16) & 0x8000) as u16;
    let exp = ((bits >> 23) & 0xff) as i32 - 127 + 15;
    let mantissa = bits & 0x007f_ffff;
    if exp <= 0 {
        return sign;
    }
    if exp >= 31 {
        return sign | 0x7c00;
    }
    let mut half = (u32::from(sign) | ((exp as u32) << 10) | (mantissa >> 13)) as u16;
    let rest = mantissa & 0x1fff;
    if rest > 0x1000 || (rest == 0x1000 && half & 1 == 1) {
        half += 1;
    }
    half
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn half_bits_match_known_values() {
        assert_eq!(half_bits(0.0), 0);
        assert_eq!(half_bits(1.0), 0x3c00);
        assert_eq!(half_bits(-2.0), 0xc000);
        assert_eq!(half_bits(0.5), 0x3800);
        assert_eq!(half_bits(65504.0), 0x7bff);
    }

    #[test]
    fn settings_from_template_tiles_and_ranges() {
        let tiles = [
            UvTile { name: "face".into(), resolution: 8192, target_texels_per_mm: 10.0 },
            UvTile { name: "torso".into(), resolution: 4096, target_texels_per_mm: 3.0 },
        ];
        let s = SurfaceSettings::for_tiles(&tiles);
        assert!((s.mm_per_uv[0] - 819.2).abs() < 1e-3);
        assert!((s.mm_per_uv[1] - 1365.333).abs() < 1e-2);
        assert_eq!(s.mm_per_uv[2], 0.0);
        assert!(s.validate().is_ok());
        assert!(SurfaceSettings { fuzz: 1.5, ..s }.validate().is_err());
        assert!(SurfaceSettings { detail_strength: f32::NAN, ..s }.validate().is_err());
        let mut bad = s;
        bad.mm_per_uv[3] = -1.0;
        assert!(bad.validate().is_err());
    }

    #[test]
    fn params_layout_matches_the_shader() {
        let mut s = SurfaceSettings::default();
        s.mm_per_uv[1] = 500.0;
        s.seed = 7;
        let bytes = s.bytes(10.24, 19.2, 2, true);
        let word = |i: usize| u32::from_le_bytes([bytes[4 * i], bytes[4 * i + 1], bytes[4 * i + 2], bytes[4 * i + 3]]);
        let float = |i: usize| f32::from_bits(word(i));
        // tiles[1] = (500, 1, 0, 0); tiles[2] has no resolved tile.
        assert_eq!(float(4), 500.0);
        assert_eq!(float(5), 1.0);
        assert_eq!(float(9), NO_TILE);
        // detail, coat, fuzz, misc after the 16 tiles.
        assert_eq!(float(64), 10.24);
        assert_eq!(float(65), s.detail_strength);
        assert_eq!(float(68), s.oil_coat);
        assert_eq!(float(72), s.fuzz);
        assert!(float(75) > 0.0);
        assert_eq!(word(76), 7);
        assert_eq!(word(77), 1);
        // misc.z, misc.w: the colour detail tile's side and strength.
        assert_eq!(float(78), 19.2);
        assert_eq!(float(79), s.albedo_detail);
    }
}
